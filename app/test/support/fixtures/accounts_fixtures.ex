defmodule App.AccountsFixtures do
  @moduledoc """
  This module defines test helpers for creating
  entities via the `App.Accounts` context.

  Generated by `mix phx.gen.auth` and adapted to Cloudflare D1. The three
  helpers that reached for `App.Repo` to backdate a token now run SQL against
  `App.D1.LocalGateway` — the test database — directly, which keeps the
  gateway's HTTP contract free of routes that exist only for tests. They need
  `App.D1Stub.stub_d1_sqlite!/1` to have run.
  """

  alias App.Accounts
  alias App.Accounts.Scope
  alias App.D1

  def unique_user_email, do: "user#{System.unique_integer()}@example.com"
  def valid_user_password, do: "hello world!"

  def valid_user_attributes(attrs \\ %{}) do
    # `password_confirmation` is part of a valid registration: the form renders
    # the field, so a submit always sends it, and `validate_confirmation/3`
    # compares it as soon as it is present — even when blank.
    Enum.into(attrs, %{
      email: unique_user_email(),
      password: valid_user_password(),
      password_confirmation: valid_user_password()
    })
  end

  def unconfirmed_user_fixture(attrs \\ %{}) do
    {:ok, user} =
      attrs
      |> valid_user_attributes()
      |> Accounts.register_user()

    user
  end

  def user_fixture(attrs \\ %{}) do
    user = unconfirmed_user_fixture(attrs)

    token =
      extract_user_token(fn url ->
        Accounts.deliver_login_instructions(user, url)
      end)

    # Registration sets a password, so confirming requires a requester already
    # logged in as this user; see `App.Accounts.login_user_by_magic_link/2`.
    {:ok, {user, _expired_tokens}} = Accounts.login_user_by_magic_link(token, user)

    user
  end

  def user_scope_fixture do
    user = user_fixture()
    user_scope_fixture(user)
  end

  def user_scope_fixture(user) do
    Scope.for_user(user)
  end

  def set_password(user) do
    {:ok, {user, _expired_tokens}} =
      Accounts.update_user_password(user, %{password: valid_user_password()})

    user
  end

  def extract_user_token(fun) do
    {:ok, captured_email} = fun.(&"[TOKEN]#{&1}[TOKEN]")
    [_, token | _] = String.split(captured_email.text_body, "[TOKEN]")
    token
  end

  def override_token_authenticated_at(token, authenticated_at) when is_binary(token) do
    update_token(token, "authenticated_at = ?2", [timestamp(authenticated_at)])
  end

  def generate_user_magic_link_token(user) do
    {encoded_token, user_token} = Accounts.UserToken.build_email_token(user, "login")

    {:ok, _row} =
      D1.create_user_token(%{
        user_id: user_token.user_id,
        token: user_token.token,
        context: user_token.context,
        sent_to: user_token.sent_to
      })

    {encoded_token, user_token.token}
  end

  def offset_user_token(token, amount_to_add, unit) do
    at = timestamp(DateTime.add(DateTime.utc_now(:second), amount_to_add, unit))
    update_token(token, "inserted_at = ?2, authenticated_at = ?2", [at])
  end

  @doc """
  Reads a user row straight from the test database.

  Rows, not structs: the point of reading back here is to see what was
  actually persisted, so the assertions stay on the database's side of
  `App.Accounts`' row conversion.
  """
  def user_row(id) do
    one("SELECT * FROM users WHERE id = ?1", [id])
  end

  @doc "Reads the token row for raw `token` bytes."
  def user_token_row(token) do
    one("SELECT * FROM users_tokens WHERE token = ?1", [D1.encode_token(token)])
  end

  @doc "Reads every token row belonging to `user_id`, oldest first."
  def user_token_rows(user_id) do
    {:ok, rows} =
      App.D1.LocalGateway.query("SELECT * FROM users_tokens WHERE user_id = ?1 ORDER BY id", [
        user_id
      ])

    rows
  end

  @doc "Backdates every token so the validity windows reject them."
  def backdate_user_tokens(at \\ ~U[2020-01-01 00:00:00Z]) do
    {:ok, _rows} =
      App.D1.LocalGateway.query(
        "UPDATE users_tokens SET inserted_at = ?1, authenticated_at = ?1",
        [timestamp(at)]
      )

    :ok
  end

  @doc "Sets a password hash directly, without going through a changeset."
  def set_hashed_password(user, hashed_password) do
    {:ok, _rows} =
      App.D1.LocalGateway.query("UPDATE users SET hashed_password = ?1 WHERE id = ?2", [
        hashed_password,
        user.id
      ])

    %{user | hashed_password: hashed_password}
  end

  defp one(sql, params) do
    {:ok, rows} = App.D1.LocalGateway.query(sql, params)
    List.first(rows)
  end

  defp update_token(token, assignments, values) do
    {:ok, _rows} =
      App.D1.LocalGateway.query(
        "UPDATE users_tokens SET #{assignments} WHERE token = ?1",
        [D1.encode_token(token) | values]
      )

    :ok
  end

  # The format every timestamp column uses; see cloudflare/migrations/0003.
  defp timestamp(%DateTime{} = at) do
    at |> DateTime.truncate(:second) |> DateTime.to_naive() |> NaiveDateTime.to_string()
  end
end
