  end

  describe "login_user_by_magic_link/2" do
    test "confirms user and expires tokens when the requester is logged in as them" do
      user = unconfirmed_user_fixture()
      refute user.confirmed_at
      {encoded_token, hashed_token} = generate_user_magic_link_token(user)

      assert {:ok, {confirmed, [%{token: ^hashed_token}]}} =
               Accounts.login_user_by_magic_link(encoded_token, user)

      assert confirmed.confirmed_at
    end

    test "refuses to confirm a password-holding account for an anonymous requester" do
      user = unconfirmed_user_fixture()
      {encoded_token, _hashed_token} = generate_user_magic_link_token(user)

      # The credential pre-stuffing mitigation: an attacker who registered this
      # address must not be let in when its owner follows the emailed link.
      assert {:error, :not_confirmable} = Accounts.login_user_by_magic_link(encoded_token)

      assert {:error, :not_confirmable} =
               Accounts.login_user_by_magic_link(encoded_token, user_fixture())

      refute user_row(user.id)["confirmed_at"]
      assert user_token_rows(user.id) != []
    end

    test "confirms an account with no password without being logged in" do
      user = unconfirmed_user_fixture()
      set_hashed_password(user, nil)
      {encoded_token, _hashed_token} = generate_user_magic_link_token(user)

      assert {:ok, {confirmed, _expired}} = Accounts.login_user_by_magic_link(encoded_token)
      assert confirmed.confirmed_at
    end

    test "returns user and (deleted) token for confirmed user" do
      user = user_fixture()
      assert user.confirmed_at
      {encoded_token, _hashed_token} = generate_user_magic_link_token(user)
      assert {:ok, {logged_in, []}} = Accounts.login_user_by_magic_link(encoded_token)
      assert logged_in.id == user.id
      # one time use only
      assert {:error, :not_found} = Accounts.login_user_by_magic_link(encoded_token)
    end
  end

  describe "delete_user_session_token/1" do
    test "deletes the token" do
      user = user_fixture()
      token = Accounts.generate_user_session_token(user)
      assert Accounts.delete_user_session_token(token) == :ok
      refute Accounts.get_user_by_session_token(token)
    end
  end

