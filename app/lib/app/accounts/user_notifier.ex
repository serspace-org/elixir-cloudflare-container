defmodule App.Accounts.UserNotifier do
  @moduledoc """
  Account emails, generated by `mix phx.gen.auth`.

  Delivery only works when `MAIL_FROM` is set, which switches `App.Mailer`
  over to `App.Mailer.Gateway` and the Worker's private mail gateway (see
  `docs/authentication.md`). The generated code assumed a provider was always
  there: `Swoosh.Adapters.Local` is otherwise the configured adapter, but
  `config/prod.exs` sets `config :swoosh, local: false`, which stops Swoosh
  from starting the Local adapter's storage process. Delivering then exits
  with `:noproc` — a 500, not a silent no-op.

  So `delivery_configured?/0` is checked before anything is sent, and callers
  get `{:error, :mailer_not_configured}` instead of an exception. Set
  `MAIL_FROM` and this guard opens by itself.
  """

  import Swoosh.Email

  alias App.Mailer
  alias App.Accounts.User

  require Logger

  @doc """
  True when `App.Mailer` can actually deliver.

  The Local adapter only works while Swoosh's storage process is running,
  which `config :swoosh, local: false` turns off — that is the production
  case this guards. Any other configured adapter is taken at its word.
  """
  @spec delivery_configured?() :: boolean()
  def delivery_configured? do
    case Application.get_env(:app, Mailer, []) |> Keyword.get(:adapter) do
      nil -> false
      Swoosh.Adapters.Local -> Application.get_env(:swoosh, :local, true)
      _other -> true
    end
  end

  # Delivers the email using the application mailer.
  defp deliver(recipient, subject, body) do
    email =
      new()
      |> to(recipient)
      |> from(Application.get_env(:app, :mail_from, {"App", "contact@example.com"}))
      |> subject(subject)
      |> text_body(body)

    if delivery_configured?() do
      with {:ok, _metadata} <- Mailer.deliver(email) do
        {:ok, email}
      end
    else
      Logger.warning("not sending #{inspect(subject)}: no mailer is configured")
      {:error, :mailer_not_configured}
    end
  end

  @doc """
  Deliver instructions to update a user email.
  """
  def deliver_update_email_instructions(user, url) do
    deliver(user.email, "Update email instructions", """

    ==============================

    Hi #{user.email},

    You can change your email by visiting the URL below:

    #{url}

    If you didn't request this change, please ignore this.

    ==============================
    """)
  end

  @doc """
  Deliver instructions to log in with a magic link.
  """
  def deliver_login_instructions(user, url) do
    case user do
      %User{confirmed_at: nil} -> deliver_confirmation_instructions(user, url)
      _ -> deliver_magic_link_instructions(user, url)
    end
  end

  defp deliver_magic_link_instructions(user, url) do
    deliver(user.email, "Log in instructions", """

    ==============================

    Hi #{user.email},

    You can log into your account by visiting the URL below:

    #{url}

    If you didn't request this email, please ignore this.

    ==============================
    """)
  end

  defp deliver_confirmation_instructions(user, url) do
    deliver(user.email, "Confirmation instructions", """

    ==============================

    Hi #{user.email},

    You can confirm your account by visiting the URL below:

    #{url}

    If you didn't create an account with us, please ignore this.

    ==============================
    """)
  end
end
