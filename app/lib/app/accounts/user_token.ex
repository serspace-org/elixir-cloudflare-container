defmodule App.Accounts.UserToken do
  @moduledoc """
  An Ecto embedded schema for session, magic link and email change tokens.

  Generated by `mix phx.gen.auth` and adapted to a project with no Repo. The
  generator's `verify_*_query/1` functions returned `Ecto.Query`s that folded
  the lookup and the expiry check into one statement; there is no query layer
  over Cloudflare D1, so each of them becomes a pair here — a `*_context/0`
  naming the row to fetch and a `*_valid?/1` applying the validity window —
  and `App.Accounts` does the fetching in between.

  Tokens are handled as raw bytes throughout, exactly as the generated
  `AppWeb.UserAuth` expects. `App.D1` hex-encodes them on the way to the
  database and back.
  """

  use Ecto.Schema

  alias App.Accounts.UserToken

  @hash_algorithm :sha256
  @rand_size 32

  # It is very important to keep the magic link token expiry short,
  # since someone with access to the email may take over the account.
  @magic_link_validity_in_minutes 15
  @change_email_validity_in_days 7
  @session_validity_in_days 14

  # Integer ids come from D1 (AUTOINCREMENT); see App.Tasks.Task.
  @primary_key {:id, :integer, []}
  embedded_schema do
    field :token, :binary
    field :context, :string
    field :sent_to, :string
    field :authenticated_at, :utc_datetime
    field :user_id, :integer

    timestamps(type: :utc_datetime, updated_at: false)
  end

  @doc """
  Generates a token that will be stored in a signed place,
  such as session or cookie. As they are signed, those
  tokens do not need to be hashed.

  The reason why we store session tokens in the database, even
  though Phoenix already provides a session cookie, is because
  Phoenix's default session cookies are not persisted, they are
  simply signed and potentially encrypted. This means they are
  valid indefinitely, unless you change the signing/encryption
  salt.

  Therefore, storing them allows individual user
  sessions to be expired. The token system can also be extended
  to store additional data, such as the device used for logging in.
  You could then use this information to display all valid sessions
  and devices in the UI and allow users to explicitly expire any
  session they deem invalid.
  """
  def build_session_token(user) do
    token = :crypto.strong_rand_bytes(@rand_size)
    dt = user.authenticated_at || DateTime.utc_now(:second)
    {token, %UserToken{token: token, context: "session", user_id: user.id, authenticated_at: dt}}
  end

  @doc "The context session tokens are stored under."
  def session_context, do: "session"

  @doc """
  True while a session token created at `inserted_at` is still valid.

  The counterpart of the generator's `where: token.inserted_at > ago(14, "day")`.
  """
  def session_token_valid?(inserted_at) do
    fresh?(inserted_at, -@session_validity_in_days, :day)
  end

  @doc """
  Builds a token and its hash to be delivered to the user's email.

  The non-hashed token is sent to the user email while the
  hashed part is stored in the database. The original token cannot be reconstructed,
  which means anyone with read-only access to the database cannot directly use
  the token in the application to gain access. Furthermore, if the user changes
  their email in the system, the tokens sent to the previous email are no longer
  valid.

  Users can easily adapt the existing code to provide other types of delivery methods,
  for example, by phone numbers.
  """
  def build_email_token(user, context) do
    build_hashed_token(user, context, user.email)
  end

  defp build_hashed_token(user, context, sent_to) do
    token = :crypto.strong_rand_bytes(@rand_size)
    hashed_token = :crypto.hash(@hash_algorithm, token)

    {Base.url_encode64(token, padding: false),
     %UserToken{
       token: hashed_token,
       context: context,
       sent_to: sent_to,
       user_id: user.id
     }}
  end

  @doc """
  Hashes an emailed token back into the value stored in the database.

  Returns `:error` for anything that is not a token this module issued.
  """
  def hash_email_token(token) when is_binary(token) do
    case Base.url_decode64(token, padding: false) do
      {:ok, decoded_token} -> {:ok, :crypto.hash(@hash_algorithm, decoded_token)}
      :error -> :error
    end
  end

  def hash_email_token(_token), do: :error

  @doc "The context magic link tokens are stored under."
  def magic_link_context, do: "login"

  @doc """
  True while a magic link token created at `inserted_at` is still valid.
  """
  def magic_link_token_valid?(inserted_at) do
    fresh?(inserted_at, -@magic_link_validity_in_minutes, :minute)
  end

  @doc """
  True while an email change token created at `inserted_at` is still valid.
  """
  def change_email_token_valid?(inserted_at) do
    fresh?(inserted_at, -@change_email_validity_in_days, :day)
  end

  defp fresh?(%DateTime{} = inserted_at, amount, unit) do
    DateTime.after?(inserted_at, DateTime.add(DateTime.utc_now(), amount, unit))
  end

  defp fresh?(_inserted_at, _amount, _unit), do: false
end
