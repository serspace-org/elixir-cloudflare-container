defmodule App.Accounts do
  @moduledoc """
  The Accounts context, generated by `mix phx.gen.auth` and then moved off
  Ecto onto Cloudflare D1.

  ## Where this differs from the generated code

  There is no Repo (see `App.D1`), so every `Repo.*` call here became a call
  to the private D1 gateway, and the token lookups the generator expressed as
  `Ecto.Query`s became a fetch by `{context, token}` plus a validity check
  from `App.Accounts.UserToken`. Two consequences worth knowing:

    * **Atomicity.** `Repo.transact/1` is gone. The two places that needed it
      — expiring every token alongside a password change or a confirmation —
      ask the gateway to do the update and the deletion in a single D1 batch,
      which is one implicit transaction. Everything else is a single
      statement, so it is atomic on its own.

    * **Uniqueness.** `unsafe_validate_unique/3` reads through the gateway
      (`App.Accounts.User.email_changeset/3`), and the unique index on
      `lower(users.email)` is what actually enforces it: a losing writer gets
      a 409, which `register_user/1` turns back into a changeset error.

  ## Registration, passwords and confirmation

  The generator registers users by email alone and makes the first login a
  magic link. This app has no mail provider yet, so `register_user/1` takes a
  password and the account is usable immediately; no email is sent.

  That choice has a documented security consequence. Quoting
  `mix help phx.gen.auth`: if users can register with a password, an attacker
  can register a victim's address, set a password, and keep access after the
  victim later confirms by magic link. The mitigation the generator prescribes
  is to require the user to be logged in at confirmation time, which is why
  `login_user_by_magic_link/2` takes the current user and refuses to confirm
  an unconfirmed account that has a password unless the requester has already
  proved they know it.

  A "forgot your password" flow is the remaining piece of that story — it is
  what lets the *victim* in when the attacker set the password — and it needs
  the mailer. See the README.
  """

  alias App.Accounts.User
  alias App.Accounts.UserNotifier
  alias App.Accounts.UserToken
  alias App.D1
  alias Ecto.Changeset

  ## Database getters

  @doc """
  Gets a user by email.

  ## Examples

      iex> get_user_by_email("foo@example.com")
      %User{}

      iex> get_user_by_email("unknown@example.com")
      nil

  """
  def get_user_by_email(email) when is_binary(email) do
    case D1.get_user_by_email(email) do
      {:ok, row} -> to_user(row)
      {:error, _reason} -> nil
    end
  end

  @doc """
  Gets a user by email and password.

  ## Examples

      iex> get_user_by_email_and_password("foo@example.com", "correct_password")
      %User{}

      iex> get_user_by_email_and_password("foo@example.com", "invalid_password")
      nil

  """
  def get_user_by_email_and_password(email, password)
      when is_binary(email) and is_binary(password) do
    user = get_user_by_email(email)
    if User.valid_password?(user, password), do: user
  end

  @doc """
  Gets a single user.

  Raises if the user does not exist, or if the D1 gateway cannot be reached.

  ## Examples

      iex> get_user!(123)
      %User{}

      iex> get_user!(456)
      ** (RuntimeError)

  """
  def get_user!(id) do
    case D1.get_user(id) do
      {:ok, row} -> to_user(row)
      {:error, :not_found} -> raise "no user with id #{inspect(id)}"
      {:error, reason} -> raise "could not read user #{inspect(id)}: #{inspect(reason)}"
    end
  end

  ## User registration

  @doc """
  Registers a user with an email and a password, and sends no email.

  See the moduledoc for why registration sets a password and what that
  obliges `login_user_by_magic_link/2` to check.

  ## Examples

      iex> register_user(%{email: ..., password: ...})
      {:ok, %User{}}

      iex> register_user(%{email: bad_value})
      {:error, %Ecto.Changeset{}}

  """
  def register_user(attrs) do
    changeset = User.registration_changeset(%User{}, attrs)

    with {:ok, user} <- Changeset.apply_action(changeset, :insert),
         {:ok, row} <-
           D1.create_user(%{email: user.email, hashed_password: user.hashed_password}) do
      {:ok, to_user(row)}
    else
      {:error, %Changeset{} = changeset} -> {:error, changeset}
      {:error, :email_taken} -> {:error, email_taken_error(changeset)}
      {:error, reason} -> {:error, reason}
    end
  end

  @doc """
  Returns an `%Ecto.Changeset{}` for registering a user.

  See `App.Accounts.User.registration_changeset/3` for supported options.
  """
  def change_user_registration(user \\ %User{}, attrs \\ %{}, opts \\ []) do
    User.registration_changeset(user, attrs, opts)
  end

  ## Settings

  @doc """
  Checks whether the user is in sudo mode.

  The user is in sudo mode when the last authentication was done no further
  than 20 minutes ago. The limit can be given as second argument in minutes.
  """
  def sudo_mode?(user, minutes \\ -20)

  def sudo_mode?(%User{authenticated_at: ts}, minutes) when is_struct(ts, DateTime) do
    DateTime.after?(ts, DateTime.utc_now() |> DateTime.add(minutes, :minute))
  end

  def sudo_mode?(_user, _minutes), do: false

  @doc """
  Returns an `%Ecto.Changeset{}` for changing the user email.

  See `App.Accounts.User.email_changeset/3` for a list of supported options.

  ## Examples

      iex> change_user_email(user)
      %Ecto.Changeset{data: %User{}}

  """
  def change_user_email(user, attrs \\ %{}, opts \\ []) do
    User.email_changeset(user, attrs, opts)
  end

  @doc """
  Updates the user email using the given token.

  If the token matches, the user email is updated and the token is deleted.
  The update and the deletion happen in one D1 batch.
  """
  def update_user_email(user, token) do
    context = "change:#{user.email}"

    with {:ok, hashed_token} <- UserToken.hash_email_token(token),
         {:ok, {token_row, _user_row}} <- D1.get_user_token(hashed_token, context),
         true <- UserToken.change_email_token_valid?(parse_timestamp(token_row["inserted_at"])),
         email when is_binary(email) <- token_row["sent_to"],
         {:ok, _validated} <-
           user |> User.email_changeset(%{email: email}) |> Changeset.apply_action(:update),
         {:ok, {row, _expired}} <-
           D1.update_user(user.id, %{email: email, delete_tokens_context: context}) do
      {:ok, to_user(row)}
    else
      _other -> {:error, :transaction_aborted}
    end
  end

  @doc """
  Returns an `%Ecto.Changeset{}` for changing the user password.

  See `App.Accounts.User.password_changeset/3` for a list of supported options.

  ## Examples

      iex> change_user_password(user)
      %Ecto.Changeset{data: %User{}}

  """
  def change_user_password(user, attrs \\ %{}, opts \\ []) do
    User.password_changeset(user, attrs, opts)
  end

  @doc """
  Updates the user password.

  Returns a tuple with the updated user, as well as a list of expired tokens.

  ## Examples

      iex> update_user_password(user, %{password: ...})
      {:ok, {%User{}, [...]}}

      iex> update_user_password(user, %{password: "too short"})
      {:error, %Ecto.Changeset{}}

  """
  def update_user_password(user, attrs) do
    with {:ok, updated} <-
           user |> User.password_changeset(attrs) |> Changeset.apply_action(:update) do
      update_user_and_expire_all_tokens(user, %{hashed_password: updated.hashed_password})
    end
  end

  ## Session

  @doc """
  Generates a session token.
  """
  def generate_user_session_token(user) do
    {token, user_token} = UserToken.build_session_token(user)

    {:ok, _row} =
      D1.create_user_token(%{
        user_id: user_token.user_id,
        token: user_token.token,
        context: user_token.context,
        authenticated_at: user_token.authenticated_at
      })

    token
  end

  @doc """
  Gets the user with the given signed token.

  If the token is valid `{user, token_inserted_at}` is returned, otherwise `nil` is returned.
  """
  def get_user_by_session_token(token) do
    with {:ok, {token_row, user_row}} <- D1.get_user_token(token, UserToken.session_context()),
         inserted_at = parse_timestamp(token_row["inserted_at"]),
         true <- UserToken.session_token_valid?(inserted_at) do
      user = %{
        to_user(user_row)
        | authenticated_at: parse_timestamp(token_row["authenticated_at"])
      }

      {user, inserted_at}
    else
      _other -> nil
    end
  end

  @doc """
  Gets the user with the given magic link token.
  """
  def get_user_by_magic_link_token(token) do
    case fetch_magic_link_token(token) do
      {:ok, {_token_row, user}} -> user
      :error -> nil
    end
  end

  @doc """
  Logs the user in by magic link.

  `current_user` is the user the request is already authenticated as, if any.

  There are three cases to consider:

  1. The user has already confirmed their email. They are logged in
     and the magic link is expired.

  2. The user has not confirmed their email and no password is set.
     In this case, the user gets confirmed, logged in, and all tokens -
     including session ones - are expired. In theory, no other tokens
     exist but we delete all of them for best security practices.

  3. The user has not confirmed their email but a password is set. This is
     the common case here, because `register_user/1` sets a password. The
     account is only confirmed when `current_user` is that same user, which
     proves the requester knows the password; otherwise this returns
     `{:error, :not_confirmable}`. See the moduledoc.
  """
  def login_user_by_magic_link(token, current_user \\ nil) do
    case fetch_magic_link_token(token) do
      {:ok, {_token_row, %User{confirmed_at: nil, hashed_password: hash} = user}}
      when not is_nil(hash) ->
        if current_user && current_user.id == user.id do
          confirm_user(user)
        else
          {:error, :not_confirmable}
        end

      {:ok, {_token_row, %User{confirmed_at: nil} = user}} ->
        confirm_user(user)

      {:ok, {token_row, user}} ->
        {:ok, _count} =
          D1.delete_user_token(D1.decode_token(token_row["token"]), token_row["context"])

        {:ok, {user, []}}

      :error ->
        {:error, :not_found}
    end
  end

  @doc ~S"""
  Delivers the update email instructions to the given user.

  ## Examples

      iex> deliver_user_update_email_instructions(user, current_email, &url(~p"/users/settings/confirm-email/#{&1}"))
      {:ok, %{to: ..., body: ...}}

  """
  def deliver_user_update_email_instructions(%User{} = user, current_email, update_email_url_fun)
      when is_function(update_email_url_fun, 1) do
    if email_delivery_available?() do
      {encoded_token, user_token} = UserToken.build_email_token(user, "change:#{current_email}")

      {:ok, _row} = insert_email_token(user_token)
      UserNotifier.deliver_update_email_instructions(user, update_email_url_fun.(encoded_token))
    else
      {:error, :mailer_not_configured}
    end
  end

  @doc """
  Delivers the magic link login instructions to the given user.
  """
  def deliver_login_instructions(%User{} = user, magic_link_url_fun)
      when is_function(magic_link_url_fun, 1) do
    if email_delivery_available?() do
      {encoded_token, user_token} = UserToken.build_email_token(user, "login")

      {:ok, _row} = insert_email_token(user_token)
      UserNotifier.deliver_login_instructions(user, magic_link_url_fun.(encoded_token))
    else
      {:error, :mailer_not_configured}
    end
  end

  @doc """
  True when account emails can actually be delivered.

  Guards the two flows that depend on email — magic link login and changing
  an email address — so they neither crash nor claim to have sent something.
  False until the Worker's mail gateway is switched on with `MAIL_FROM`; see
  `docs/authentication.md`.

  The token is deliberately not created when this is false: an unusable magic
  link should not exist in the database at all.
  """
  @spec email_delivery_available?() :: boolean()
  def email_delivery_available?, do: UserNotifier.delivery_configured?()

  @doc """
  Deletes the signed token with the given context.
  """
  def delete_user_session_token(token) do
    D1.delete_user_token(token, UserToken.session_context())
    :ok
  end

  ## Token helpers

  defp insert_email_token(%UserToken{} = user_token) do
    D1.create_user_token(%{
      user_id: user_token.user_id,
      token: user_token.token,
      context: user_token.context,
      sent_to: user_token.sent_to
    })
  end

  # The generator folded this into `UserToken.verify_magic_link_token_query/1`.
  # The `sent_to` check is the part that invalidates links mailed to an address
  # the user has since changed away from.
  defp fetch_magic_link_token(token) do
    with {:ok, hashed_token} <- UserToken.hash_email_token(token),
         {:ok, {token_row, user_row}} <-
           D1.get_user_token(hashed_token, UserToken.magic_link_context()),
         true <- UserToken.magic_link_token_valid?(parse_timestamp(token_row["inserted_at"])),
         user = to_user(user_row),
         true <- token_row["sent_to"] == user.email do
      {:ok, {token_row, user}}
    else
      _other -> :error
    end
  end

  defp confirm_user(%User{} = user) do
    {:ok, confirmed} = user |> User.confirm_changeset() |> Changeset.apply_action(:update)
    update_user_and_expire_all_tokens(user, %{confirmed_at: confirmed.confirmed_at})
  end

  # One D1 batch, so the user never ends up changed with their old sessions
  # still live — the guarantee the generator got from `Repo.transact/1`.
  defp update_user_and_expire_all_tokens(%User{} = user, attrs) do
    case D1.update_user(user.id, Map.put(attrs, :delete_all_tokens, true)) do
      {:ok, {row, expired}} -> {:ok, {to_user(row), Enum.map(expired, &to_user_token/1)}}
      {:error, :email_taken} -> {:error, email_taken_error(User.email_changeset(user, %{}))}
      {:error, _reason} = error -> error
    end
  end

  defp email_taken_error(%Changeset{} = changeset) do
    changeset
    |> Changeset.add_error(:email, "has already been taken")
    |> Map.put(:action, :insert)
  end

  ## Row conversion

  defp to_user(row) do
    %User{
      id: row["id"],
      email: row["email"],
      hashed_password: row["hashed_password"],
      confirmed_at: parse_timestamp(row["confirmed_at"]),
      inserted_at: parse_timestamp(row["inserted_at"]),
      updated_at: parse_timestamp(row["updated_at"])
    }
  end

  defp to_user_token(row) do
    %UserToken{
      id: row["id"],
      user_id: row["user_id"],
      token: D1.decode_token(row["token"]),
      context: row["context"],
      sent_to: row["sent_to"],
      authenticated_at: parse_timestamp(row["authenticated_at"]),
      inserted_at: parse_timestamp(row["inserted_at"])
    }
  end

  # Timestamp columns are TEXT in SQLite's CURRENT_TIMESTAMP format, always
  # UTC; the generated code works in `DateTime`s.
  defp parse_timestamp(nil), do: nil

  defp parse_timestamp(timestamp) when is_binary(timestamp) do
    case NaiveDateTime.from_iso8601(timestamp) do
      {:ok, naive} -> DateTime.from_naive!(naive, "Etc/UTC")
      {:error, _reason} -> nil
    end
  end
end
