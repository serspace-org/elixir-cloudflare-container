defmodule App.Chat.Room do
  @moduledoc """
  An Ecto embedded schema for chat rooms.

  Used for casting and validation only, like `App.Tasks.Task`. Rows live in
  Cloudflare D1 and are persisted through the private gateway in `App.D1` —
  there is no Repo. A room that was never claimed has no row at all (it is
  an implicit link room), so most slugs passing through `App.Chat` never
  become one of these structs.
  """

  use Ecto.Schema
  import Ecto.Changeset

  @visibilities ~w(link private)

  # Integer ids come from D1 (AUTOINCREMENT); see App.Tasks.Task for why
  # the primary key is declared without autogenerate.
  @primary_key {:id, :integer, []}
  embedded_schema do
    field :slug, :string
    field :user_id, :integer
    field :name, :string
    field :visibility, :string, default: "private"
    # The caller's relationship to the room (:owner, :member or :link),
    # resolved by the gateway — never persisted.
    field :role, Ecto.Enum, values: [:owner, :member, :link], virtual: true
    field :inserted_at, :naive_datetime
    field :updated_at, :naive_datetime
  end

  @type t :: %__MODULE__{}

  @doc "The visibilities a room can have."
  def visibilities, do: @visibilities

  @doc """
  Casts and validates the attributes a user controls (`name`, `visibility`).

  The slug is deliberately not castable: it is generated by
  `App.Chat.new_room/0` and validated by `App.Chat.valid_room?/1`, never
  typed in.
  """
  def changeset(room, attrs) do
    room
    |> cast(attrs, [:name, :visibility])
    |> update_change(:name, &trim_to_nil/1)
    |> validate_length(:name, max: 160)
    |> validate_required([:visibility])
    |> validate_inclusion(:visibility, @visibilities)
  end

  defp trim_to_nil(name) when is_binary(name) do
    case String.trim(name) do
      "" -> nil
      trimmed -> trimmed
    end
  end

  defp trim_to_nil(name), do: name
end
