# Guarded like App.MigrationRepo: the SQLite adapter is a dev/test dep, and
# this task has no business existing in a production release.
if Mix.env() != :prod do
  defmodule Mix.Tasks.D1.GenMigrations do
    @shortdoc "Exports cloudflare/migrations/*.sql from the Ecto migrations"

    @moduledoc """
    Runs the Ecto migrations in `priv/migration_repo/migrations/` against a
    throwaway SQLite database (the engine D1 runs) and exports the SQL each
    one executed as `cloudflare/migrations/<version>_<name>.sql` — the files
    Wrangler applies to D1 in CI and `App.D1.LocalGateway` applies locally.

        $ cd app && mix d1.gen_migrations

    The authoring flow for a schema change is therefore:

      1. add an Ecto migration, e.g.
         `priv/migration_repo/migrations/0007_add_pins.exs`
         (next version number, zero-padded, snake-case name);
      2. run `mix d1.gen_migrations` and commit both files;
      3. `App.D1.MigrationParityTest` proves the exported SQL and the Ecto
         path build the same schema.

    A `.sql` file that already exists is **never rewritten**: D1 and the
    local gateway track applied migrations by file name, so changing a
    shipped file would either be ignored silently or break the deploy. To
    change the schema, add a new migration.
    """

    use Mix.Task

    @impl true
    def run(_args) do
      Mix.Task.run("app.config")
      {:ok, _apps} = Application.ensure_all_started(:ecto_sqlite3)

      out_dir = Path.expand("../cloudflare/migrations", File.cwd!())
      File.exists?(out_dir) || Mix.raise("expected #{out_dir} to exist; run from app/")

      database =
        Path.join(System.tmp_dir!(), "d1_gen_#{System.unique_integer([:positive])}.sqlite3")

      Application.put_env(:app, App.MigrationRepo, database: database, pool_size: 1)
      {:ok, _pid} = App.MigrationRepo.start_link()
      {:ok, agent} = Agent.start_link(fn -> [] end)

      handler_id = "d1-gen-migrations"

      :ok =
        :telemetry.attach(
          handler_id,
          [:app, :migration_repo, :query],
          &__MODULE__.handle_query/4,
          agent
        )

      try do
        migrations_path = App.MigrationRepo.migrations_path()

        # One migration at a time, so each capture belongs to one file.
        for {:down, version, name} <-
              Enum.sort(Ecto.Migrator.migrations(App.MigrationRepo, [migrations_path])) do
          Agent.update(agent, fn _statements -> [] end)
          Ecto.Migrator.run(App.MigrationRepo, [migrations_path], :up, to: version)

          statements =
            agent |> Agent.get(& &1) |> Enum.reverse() |> Enum.filter(&schema_statement?/1)

          file = Path.join(out_dir, "#{pad(version)}_#{name}.sql")

          cond do
            File.exists?(file) ->
              Mix.shell().info("  unchanged #{Path.basename(file)} (already shipped)")

            statements == [] ->
              Mix.raise("no SQL captured for migration #{name}")

            true ->
              File.write!(file, render(statements, version, name))
              Mix.shell().info("* exported  #{Path.basename(file)}")
          end
        end
      after
        :telemetry.detach(handler_id)
        File.rm_rf!(database)
      end
    end

    @doc false
    def handle_query(_event, _measurements, %{query: query}, agent) do
      Agent.update(agent, fn statements -> [query | statements] end)
    end

    # Everything the migrator runs for its own bookkeeping is noise; only
    # the DDL (and any data statements) the migration itself issued belongs
    # in the exported file.
    defp schema_statement?(query) do
      query = String.trim(query)

      not String.contains?(query, "schema_migrations") and
        not Enum.any?(
          ["SELECT", "PRAGMA", "BEGIN", "COMMIT", "ROLLBACK", "SAVEPOINT", "RELEASE"],
          &String.starts_with?(String.upcase(query), &1)
        )
    end

    defp render(statements, version, name) do
      header = """
      -- Exported from app/priv/migration_repo/migrations/#{pad(version)}_#{name}.exs
      -- by `mix d1.gen_migrations`. Author schema changes in that Ecto migration
      -- and re-run the task; do not edit this file by hand.
      """

      body = Enum.map_join(statements, "\n\n", &(String.trim_trailing(&1) <> ";"))
      header <> "\n" <> body <> "\n"
    end

    defp pad(version), do: version |> Integer.to_string() |> String.pad_leading(4, "0")
  end
end
